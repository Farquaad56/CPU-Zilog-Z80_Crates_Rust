#!/usr/bin/env python3
"""Download the Z80 test ROMs into tests/roms/ and verify them (Python 3.8+, stdlib only).

Usage:
  python docs/tools/fetch_roms.py [--only prelim,zexdoc,zexall]   download (default: all CP/M ROMs)
  python docs/tools/fetch_roms.py --verify [--only ...]           check size + SHA-256 of what is present
  python docs/tools/fetch_roms.py --write-manifest                recompute tests/manifest.toml
  python docs/tools/fetch_roms.py --optional singlestep,z80test   git clone --depth 1 (OPTIONAL sources)

Never downloads any ZX Spectrum ROM: zx48.rom must be provided by the user.
"""
import argparse
import hashlib
import os
import subprocess
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ROMS = os.path.join(ROOT, "tests", "roms")
MANIFEST = os.path.join(ROOT, "tests", "manifest.toml")

BASE = "https://raw.githubusercontent.com/superzazu/z80/master/roms/"
# name -> (file name, url, expected size in bytes)
CPM = {
    "prelim": ("prelim.com", BASE + "prelim.com", 1280),
    "zexdoc": ("zexdoc.cim", BASE + "zexdoc.cim", 8588),
    "zexall": ("zexall.cim", BASE + "zexall.cim", 8588),
}

# OPTIONAL sources: shallow git clones into tests/roms/<name>/.
OPTIONAL = {
    "singlestep": "https://github.com/SingleStepTests/z80",
    "z80test": "https://github.com/raxoft/z80test",
}


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def read_manifest():
    """Minimal parser for the [[rom]] tables of tests/manifest.toml."""
    entries = {}
    if not os.path.exists(MANIFEST):
        return entries
    cur = None
    with open(MANIFEST, "r", encoding="ascii") as f:
        for raw in f:
            line = raw.strip()
            if line == "[[rom]]":
                cur = {}
            elif "=" in line and cur is not None and not line.startswith("#"):
                k, v = line.split("=", 1)
                v = v.strip().strip('"')
                cur[k.strip()] = int(v) if k.strip() == "size" else v
                if "name" in cur and "sha256" in cur and "size" in cur and "url" in cur:
                    entries[cur["name"]] = cur
    return entries


def write_manifest(names):
    lines = ["# Test ROM manifest (generated by docs/tools/fetch_roms.py --write-manifest).", ""]
    for key in names:
        fname, url, _ = CPM[key]
        path = os.path.join(ROMS, fname)
        lines += [
            "[[rom]]",
            'name = "%s"' % fname,
            'url = "%s"' % url,
            "size = %d" % os.path.getsize(path),
            'sha256 = "%s"' % sha256(path),
            "",
        ]
    with open(MANIFEST, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", MANIFEST)


def fetch(names):
    os.makedirs(ROMS, exist_ok=True)
    manifest = read_manifest()
    ok = True
    for key in names:
        fname, url, size = CPM[key]
        dest = os.path.join(ROMS, fname)
        print("fetch", url)
        with urllib.request.urlopen(url, timeout=60) as r:
            data = r.read()
        if len(data) != size:
            print("ERROR %s: %d bytes, expected %d" % (fname, len(data), size))
            ok = False
            continue
        digest = hashlib.sha256(data).hexdigest()
        want = manifest.get(fname, {}).get("sha256")
        if want and want != digest:
            print("ERROR %s: sha256 %s != manifest %s" % (fname, digest, want))
            ok = False
            continue
        with open(dest, "wb") as f:
            f.write(data)
        print("ok   %s (%d bytes) %s" % (fname, size, digest))
    return ok


def verify(names):
    manifest = read_manifest()
    ok = True
    for key in names:
        fname, _, size = CPM[key]
        path = os.path.join(ROMS, fname)
        if not os.path.exists(path):
            print("skip %s (not present)" % fname)
            continue
        entry = manifest.get(fname)
        if entry is None:
            print("ERROR %s: no manifest entry" % fname)
            ok = False
        elif os.path.getsize(path) != entry["size"] or sha256(path) != entry["sha256"]:
            print("ERROR %s: size/sha256 mismatch" % fname)
            ok = False
        else:
            print("ok   %s" % fname)
    return ok


def clone(names):
    ok = True
    for key in names:
        dest = os.path.join(ROMS, key)
        if os.path.isdir(dest):
            print("skip %s (already cloned)" % key)
            continue
        os.makedirs(ROMS, exist_ok=True)
        rc = subprocess.call(["git", "clone", "--depth", "1", OPTIONAL[key], dest])
        ok = ok and rc == 0
    return ok


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--only", help="comma list among: " + ",".join(CPM))
    ap.add_argument("--verify", action="store_true")
    ap.add_argument("--write-manifest", action="store_true")
    ap.add_argument("--optional", help="comma list among: " + ",".join(OPTIONAL))
    a = ap.parse_args()
    names = a.only.split(",") if a.only else list(CPM)
    for n in names:
        if n not in CPM:
            ap.error("unknown ROM: " + n)
    if a.optional:
        opt = a.optional.split(",")
        for n in opt:
            if n not in OPTIONAL:
                ap.error("unknown optional source: " + n)
        return 0 if clone(opt) else 1
    if a.write_manifest:
        write_manifest(names)
        return 0
    return 0 if (verify(names) if a.verify else fetch(names)) else 1


if __name__ == "__main__":
    sys.exit(main())
