#!/usr/bin/env python3
"""Turn the JSON written by `z80 suite all --json out.json` into a Markdown table.

Usage: python docs/tools/suites_report.py out.json [docs/SUITES_REPORT.md]
Without the second argument the table is printed on stdout.
"""
import json
import sys


def table(data):
    lines = [
        "| Suite | Status | Seconds | Details |",
        "|---|---|---|---|",
    ]
    for s in data.get("suites", []):
        details = str(s.get("details", "")).replace("|", "/").replace("\n", " ")
        lines.append(
            "| {} | {} | {:.1f} | {} |".format(
                s.get("name", "?"), s.get("status", "?"), float(s.get("seconds", 0)), details
            )
        )
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) < 2:
        sys.stderr.write(__doc__)
        return 2
    with open(argv[1], encoding="utf-8") as f:
        data = json.load(f)
    text = "# Suites report\n\nGenerated by `z80 suite all --json` and docs/tools/suites_report.py.\n\n"
    text += table(data)
    if len(argv) > 2:
        with open(argv[2], "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
